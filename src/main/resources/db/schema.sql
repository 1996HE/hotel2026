CREATE TABLE IF NOT EXISTS reservation_guests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id integer NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  guest_name varchar(100) NOT NULL,
  guest_kana varchar(100),
  guest_gender varchar(20),
  guest_age integer,
  guest_phone varchar(50),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE reservation_guests ADD COLUMN IF NOT EXISTS guest_gender varchar(20);
ALTER TABLE reservation_guests ADD COLUMN IF NOT EXISTS guest_age integer;

CREATE INDEX IF NOT EXISTS ix_reservation_guests_reservation_id ON reservation_guests (reservation_id);

CREATE OR REPLACE VIEW checkout_reservations AS
SELECT id, reservation_no, room_id, check_in_date, check_out_date, guest_name, guest_kana, guest_gender, guest_age, guest_phone, guest_email, guest_count, reservation_form, payment_status, reservation_status, total_amount, note, created_at, updated_at
FROM reservations
WHERE reservation_status = 'checked_out';
