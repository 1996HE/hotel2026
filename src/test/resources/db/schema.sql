CREATE TABLE IF NOT EXISTS reservation_finances (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id INTEGER NOT NULL UNIQUE,
  received_amount DECIMAL(10, 2) NOT NULL DEFAULT 0,
  payment_method VARCHAR(30),
  received_at TIMESTAMP,
  refund_amount DECIMAL(10, 2) NOT NULL DEFAULT 0,
  refunded_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_finance_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE CASCADE,
  CONSTRAINT ck_finance_refund_not_over_received CHECK (refund_amount <= received_amount)
);

