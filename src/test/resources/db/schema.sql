CREATE TABLE IF NOT EXISTS public_booking_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_no VARCHAR(18) NOT NULL UNIQUE,
  locale VARCHAR(5) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  check_in_date DATE NOT NULL,
  check_out_date DATE NOT NULL,
  lead_name VARCHAR(100) NOT NULL,
  lead_email VARCHAR(255) NOT NULL,
  lead_phone VARCHAR(50) NOT NULL,
  country VARCHAR(100) NOT NULL,
  guest_count INTEGER NOT NULL,
  total_amount DECIMAL(12, 2) NOT NULL,
  notes VARCHAR(1000),
  cancel_token_hash CHAR(64) NOT NULL UNIQUE,
  hold_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  confirmed_at TIMESTAMP WITH TIME ZONE,
  rejected_at TIMESTAMP WITH TIME ZONE,
  cancelled_at TIMESTAMP WITH TIME ZONE,
  rejection_reason VARCHAR(1000),
  cancellation_reason VARCHAR(1000),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_public_booking_cancellation_reason CHECK (
    status != 'cancelled' OR NULLIF(TRIM(cancellation_reason), '') IS NOT NULL
  )
);

CREATE SEQUENCE IF NOT EXISTS public_booking_request_no_seq START WITH 1 INCREMENT BY 1 MINVALUE 1;

